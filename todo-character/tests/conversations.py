"""~100 hand-written conversations for homebot's face (conversation-level tests).

Every EXPECTED expression set and level on a user turn was decided by reading
the line as a person would, BEFORE running any code, and is never adjusted to
match output. A set means "any of these would be a fair face for this line".

Turn kinds
  U(text, expected, level, at=None, busy=False)
      user line. `at`: arrives this fraction of the way through the previous
      homebot utterance (an interruption). `busy`: sent while the brain is
      still working on the previous user line (no reply in between).
  H(text, states)
      homebot reply. states is a '>'-joined chain of Brain states driven
      before the reply is spoken, e.g. "think>tool>success>think>speak".
      Short names: think, tool, success, speak, refused, stuck, unknown, sleep.
  TOUCH(kind, region, at=None)
      kind: poke | stroke | hold | poke5.  `at` as for U.
  QUIET(seconds)      nobody does anything.
  PLAY(sequence, at=None)  a "!sequence" typed by the user.
"""

from __future__ import annotations


def U(text, expected, level="mid", at=None, busy=False):
    return {"kind": "user", "text": text, "expected": set(expected.split("|")),
            "level": set(level.split("|")), "at": at, "busy": busy}


def H(text, states="think>speak"):
    return {"kind": "homebot", "text": text, "states": states.split(">")}


def TOUCH(kind, region="panel", at=None):
    return {"kind": "touch", "touch": kind, "region": region, "at": at}


def QUIET(seconds):
    return {"kind": "quiet", "seconds": seconds}


def PLAY(name, at=None):
    return {"kind": "play", "name": name, "at": at}


def C(cid, length, scenario, *turns):
    return {"id": cid, "length": length, "scenario": scenario, "turns": list(turns)}


