def expand(phrase: str) -> list[str]:
    """'get|gets on {poss} nerves' -> every concrete phrase."""
    phrase = phrase.replace("{poss}", POSS).replace("{obj}", OBJ)
    slots = []
    for tok in phrase.split():
        opt = tok.endswith("?") and len(tok) > 1
        alts = tok.rstrip("?").split("|") if opt else tok.split("|")
        if opt:
            alts = alts + [""]
        slots.append(alts)
    out = []
    for combo in itertools.product(*slots):
        out.append(" ".join(t for t in combo if t))
    return out


_CANON_SUB = [("chh", "ch"), ("kh", "k"), ("gh", "g"), ("jh", "j"), ("z", "j"),
              ("bh", "b"), ("dh", "d"), ("th", "t"), ("ph", "f"), ("w", "v"), ("q", "k"),
              ("oo", "u"), ("ee", "i"), ("aa", "a"), ("ii", "i"), ("uu", "u")]
_DOUBLE = re.compile(r"([a-z])\1+")


def canon(w: str) -> str:
    """One spelling for the many ways a romanised word is typed:
    khooshi / khushi -> kushi, aalay / aala -> ala, accha / achha -> acha."""
    if not w.isascii() or not w.isalpha() or len(w) < 3:
        return w
    for a, b in _CANON_SUB:
        if a in w:
            w = w.replace(a, b)
    w = _DOUBLE.sub(r"\1", w)
    if len(w) > 3 and w.endswith("ay"):
        w = w[:-1]                       # aalay -> ala, radu yetay -> yeta
    elif len(w) > 3 and w.endswith("ai") and not w.endswith("hai"):
        w = w[:-1]                       # gayi / gai
    return w


def canon_words(phrase: str) -> str:
    return " ".join(canon(t) for t in phrase.split())

